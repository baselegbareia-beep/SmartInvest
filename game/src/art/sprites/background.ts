/**
 * Background: bg_* decoration tiles and the two backdrop_* pictures
 * (docs/ART-AND-SOUND.md, sections 4 and 6).
 *
 * - The bg_* tiles go on the tile sheet (16 x 16 cells; the porthole is four of them).
 *   They sit in empty cells that touch structure, never collide and never animate.
 *   bg_panel is laid first; pipes, vent, brace, chain and hook are laid over it, so
 *   everything in them except the object itself is transparent. src/art/tilePick.ts
 *   says which goes where.
 * - bg_panel has two looks, not two animation frames: 0 plain, 1 seamed.
 * - bg_porthole brings its own night surround and has no panel under it: its glass
 *   is clear, so the stars show through.
 * - The backdrop pictures go on the sprite sheet: a crescent Earth placed once per
 *   level, and a crater ridge repeated along the bottom (its left and right edges
 *   join up, and its lowest rows are plain night, so the ground can be continued
 *   below it with a night rectangle).
 * - Far things are dark: void, night, indigo and slate. Nothing here may compete with
 *   anything the player must see. The Earth alone is lighter, in the blue-greys of
 *   structure (the blues belong to coolant), and its night side is void.
 *
 * To see your work:  node src/art/tools/preview.ts sheet background <out.png>
 *                    node src/art/tools/scene.ts levels/debug.txt --window 0,0 <out.png>
 */
